package frames

import (
	"image"
	"image/color"
)

const (
	glyphW, glyphH = 5, 7
	labelScale     = 2
	labelMargin    = 2
	glyphAdvance   = glyphW + 1
)

var (
	labelInk = color.RGBA{R: 255, G: 255, B: 0, A: 255}
	labelBox = color.RGBA{A: 255}
)

// DrawLabel draws text at the top-left of img: yellow 5x7 glyphs at scale 2
// on a black box with a 2 px margin. Text that does not fit is clipped, never
// wrapped, and a rune outside printable ASCII is drawn as '?'.
func DrawLabel(img *image.RGBA, text string) {
	if img == nil || text == "" {
		return
	}
	runes := []rune(text)
	ox, oy := img.Rect.Min.X, img.Rect.Min.Y
	boxW := labelMargin*2 + (len(runes)*glyphAdvance-1)*labelScale
	boxH := labelMargin*2 + glyphH*labelScale
	for y := 0; y < boxH; y++ {
		for x := 0; x < boxW; x++ {
			img.SetRGBA(ox+x, oy+y, labelBox)
		}
	}
	for i, r := range runes {
		g := glyphFor(r)
		gx := ox + labelMargin + i*glyphAdvance*labelScale
		for row := 0; row < glyphH; row++ {
			for col := 0; col < glyphW; col++ {
				if g[row]&(1<<(glyphW-1-col)) == 0 {
					continue
				}
				for dy := 0; dy < labelScale; dy++ {
					for dx := 0; dx < labelScale; dx++ {
						img.SetRGBA(gx+col*labelScale+dx, oy+labelMargin+row*labelScale+dy, labelInk)
					}
				}
			}
		}
	}
}

func glyphFor(r rune) [glyphH]uint8 {
	if r < ' ' || r > '~' {
		r = '?'
	}
	return font[r-' ']
}

// font holds one row mask per glyph row, bit 4 the leftmost pixel, built from
// the string art in glyphArt.
var font = func() (f [95][glyphH]uint8) {
	for r := ' '; r <= '~'; r++ {
		art, ok := glyphArt[r]
		if !ok {
			panic("label font has no glyph for " + string(r))
		}
		for row, line := range art {
			if len(line) != glyphW {
				panic("label font glyph " + string(r) + " has a row that is not 5 wide")
			}
			for col := 0; col < glyphW; col++ {
				switch line[col] {
				case '#':
					f[r-' '][row] |= 1 << (glyphW - 1 - col)
				case '.':
				default:
					panic("label font glyph " + string(r) + " has a stray character")
				}
			}
		}
	}
	return f
}()

