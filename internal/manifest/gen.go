package manifest

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/reclyptor/mediaops/internal/cli"
)

const generatedNote = "generated by mkv-manifest gen %s; review before exec"

// Generated is a manifest a generator wrote. Marshaled, it is a file Load
// accepts as it stands.
type Generated struct {
	Name      string  `json:"name,omitempty"`
	Note      string  `json:"note,omitempty"`
	Generated GenInfo `json:"generated"`
	Ops       []Op    `json:"ops"`
}

// GenInfo records how a manifest came to be. Load ignores it.
type GenInfo struct {
	By   string   `json:"by"`
	Args []string `json:"args"`
	At   string   `json:"at"`

	// Unmatched lists what rename-series saw and left alone, relative to DIR.
	Unmatched []string `json:"unmatched,omitempty"`
}

var (
	episodeName = regexp.MustCompile(`^(?P<old>.+?) - S(?P<s>\d{2})E(?P<e>\d{2}(?:\.\d+)?)(?P<rest>(?: - .*?)?(?: \(OVA\))?\.[A-Za-z0-9]+)$`)
	seasonDir   = regexp.MustCompile(`^Season (\d+)$`)
	trailingDay = regexp.MustCompile(` - \[\d{4}-\d{2}-\d{2}\](\.[A-Za-z0-9]+)$`)
)

// GenRenameSeries writes the manifest that renames a series' episodes to name
// and pads its Season folders, the work rename-series.py did in place. only
// limits it to those season numbers; nil or empty means every season.
func GenRenameSeries(dir, name string, only []int, stripDate bool, now time.Time) (Generated, error) {
	given := dir
	if dir == "" {
		return Generated{}, cli.Usage(errors.New("no such directory: the directory is empty"))
	}
	if name == "" || strings.ContainsRune(name, '/') {
		return Generated{}, cli.Usage(fmt.Errorf("the series name %q must be non-empty and hold no '/'", name))
	}
	dir, err := filepath.Abs(dir)
	if err != nil {
		return Generated{}, cli.Usage(fmt.Errorf("cannot resolve %s: %w", given, err))
	}
	if !realDir(dir) {
		return Generated{}, cli.Usage(fmt.Errorf("no such directory: %s", dir))
	}

	chosen := map[int]bool{}
	for _, n := range only {
		chosen[n] = true
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return Generated{}, fmt.Errorf("reading %s: %w", dir, err)
	}

	var (
		moves, rmdirs []Op
		unmatched     []string
		seasons       int
		episodes      int
	)
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		m := seasonDir.FindStringSubmatch(entry.Name())
		if m == nil {
			continue
		}
		number, err := strconv.Atoi(m[1])
		if err != nil || (len(chosen) > 0 && !chosen[number]) {
			continue
		}
		seasons++

		padded := fmt.Sprintf("Season %02d", number)
		srcDir := filepath.Join(dir, entry.Name())
		dstDir := filepath.Join(dir, padded)
		padding := entry.Name() != padded

		files, err := os.ReadDir(srcDir)
		if err != nil {
			return Generated{}, fmt.Errorf("reading %s: %w", srcDir, err)
		}
		for _, f := range files {
			src := filepath.Join(srcDir, f.Name())
			rel := filepath.Join(entry.Name(), f.Name())
			if f.Type().IsRegular() {
				info, err := f.Info()
				if err != nil {
					return Generated{}, fmt.Errorf("reading %s: %w", src, err)
				}
				size := info.Size()
				dstName := f.Name()
				if em := episodeName.FindStringSubmatch(f.Name()); em != nil {
					episodes++
					rest := em[episodeName.SubexpIndex("rest")]
					if stripDate {
						rest = trailingDay.ReplaceAllString(rest, "$1")
					}
					dstName = fmt.Sprintf("%s - S%sE%s%s", name,
						em[episodeName.SubexpIndex("s")], em[episodeName.SubexpIndex("e")], rest)
				} else if !padding {
					unmatched = append(unmatched, rel)
					continue
				}
				dst := filepath.Join(dstDir, dstName)
				if dst != src {
					moves = append(moves, Op{Kind: KindRename, Src: src, Dst: dst, Size: &size})
				}
				continue
			}
			if padding && f.IsDir() {
				moves = append(moves, Op{Kind: KindMoveDir, Src: src, Dst: filepath.Join(dstDir, f.Name())})
				continue
			}
			unmatched = append(unmatched, rel)
		}
		if padding {
			rmdirs = append(rmdirs, Op{Kind: KindRmdirIfEmpty, Path: srcDir})
		}
	}

	switch {
	case seasons == 0:
		return Generated{}, cli.Usage(fmt.Errorf("no Season directories in %s", dir))
	case episodes == 0:
		return Generated{}, cli.Usage(fmt.Errorf("no episode files in the chosen Season directories of %s", dir))
	case len(moves) == 0:
		return Generated{}, cli.Usage(fmt.Errorf("nothing to rename in %s", dir))
	}

	args := []string{given, name}
	if len(only) > 0 {
		parts := make([]string, len(only))
		for i, n := range only {
			parts[i] = strconv.Itoa(n)
		}
		args = append(args, "--only", strings.Join(parts, ","))
	}
	if stripDate {
		args = append(args, "--strip-date")
	}
	return Generated{
		Name: name,
		Note: fmt.Sprintf(generatedNote, "rename-series"),
		Generated: GenInfo{
			By:        "mkv-manifest gen rename-series",
			Args:      args,
			At:        now.UTC().Format(time.RFC3339),
			Unmatched: unmatched,
		},
		Ops: append(moves, rmdirs...),
	}, nil
}

// GenArchiveTree writes the manifest that archives every file under src to the
// same relative path under dst and then clears src's emptied directories.
func GenArchiveTree(src, dst string, now time.Time) (Generated, error) {
	givenSrc, givenDst := src, dst
	if src == "" || dst == "" {
		return Generated{}, cli.Usage(errors.New("gen archive-tree needs a source and a destination"))
	}
	src, err := filepath.Abs(src)
	if err != nil {
		return Generated{}, cli.Usage(fmt.Errorf("cannot resolve %s: %w", givenSrc, err))
	}
	dst, err = filepath.Abs(dst)
	if err != nil {
		return Generated{}, cli.Usage(fmt.Errorf("cannot resolve %s: %w", givenDst, err))
	}
	if !realDir(src) {
		return Generated{}, cli.Usage(fmt.Errorf("source is not a real directory: %s", src))
	}
	if within(src, dst) {
		return Generated{}, cli.Usage(fmt.Errorf("destination %s lies inside the source %s", dst, src))
	}

	var files, dirs []string
	var ops []Op
	err = filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		switch {
		case d.IsDir():
			dirs = append(dirs, path)
		case d.Type().IsRegular():
			info, err := d.Info()
			if err != nil {
				return err
			}
			rel, err := filepath.Rel(src, path)
			if err != nil {
				return err
			}
			size := info.Size()
			files = append(files, path)
			ops = append(ops, Op{Kind: KindArchiveFile, Src: path, Dst: filepath.Join(dst, rel), Size: &size})
		default:
			return cli.Usage(fmt.Errorf("%s is a symlink or special file; archive-tree moves only regular files", path))
		}
		return nil
	})
	if err != nil {
		if cli.Code(err) == cli.ExitUsage {
			return Generated{}, err
		}
		return Generated{}, fmt.Errorf("reading the tree of %s: %w", src, err)
	}
	if len(files) == 0 {
		return Generated{}, cli.Usage(fmt.Errorf("source is empty: %s holds no files", src))
	}

	depth := func(p string) int { return strings.Count(p, string(filepath.Separator)) }
	sort.SliceStable(dirs, func(i, j int) bool {
		if di, dj := depth(dirs[i]), depth(dirs[j]); di != dj {
			return di > dj
		}
		return dirs[i] < dirs[j]
	})
	for _, d := range dirs {
		ops = append(ops, Op{Kind: KindRmdirIfEmpty, Path: d})
	}

	return Generated{
		Name: filepath.Base(src),
		Note: fmt.Sprintf(generatedNote, "archive-tree"),
		Generated: GenInfo{
			By:   "mkv-manifest gen archive-tree",
			Args: []string{givenSrc, givenDst},
			At:   now.UTC().Format(time.RFC3339),
		},
		Ops: ops,
	}, nil
}
